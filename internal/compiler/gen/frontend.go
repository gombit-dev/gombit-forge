// FrontendRoot is the compiler-owned frontend directory (ADR-001 §64).
const FrontendRoot = "frontend/src/forge_generated"

// tsBanner marks a generated TypeScript/TSX file as compiler-owned. It is a
// block comment so it is valid at the top of a .tsx module.
const tsBanner = "/* Code generated by Gombit Forge. DO NOT EDIT. */"

// Frontend generates the React CRUD pages and the resource registry under
// frontend/src/forge_generated/ (DESIGN.md §9 stages 7–9, ADR-001 §64).
//
// Table (list) pages are page-driven (M3, #51): one is emitted per
// resource_table page in the spec's Pages graph, honoring the page's slug (its
// route), title and configured columns. A resource with no resource_table page
// gets no list page — there is no implicit per-resource list — and two
// resource_table pages targeting one resource produce two independent tables.
//
// Detail and form pages remain resource-driven for now (their page-driven
// builders are #53 and #52): per resource a detail page (always) and a form
// page when create or update is enabled. The form POSTs when create is enabled
// and PUTs when update is enabled, so the pages honor the same CRUD toggles the
// handlers route (DESIGN.md §4.3). A detail/form page's "back to list" link
// targets the resource's first table page, or is omitted when it has none.
//
// The pages are ordinary consumers of Gombit's generated OpenAPI client
// (ADR-004 D3): useApiClient, unwrap, applyContractErrors and the paths/schema
// types produced by `gombit client generate` (DESIGN.md P4). Forge does not
// hand-roll the TypeScript client.
//
// Files come back in a stable order: per-resource detail/form pages in authored
// resource order, then the table pages in authored page order, then the
// registry.
func Frontend(g *graph.Graph) ([]File, error) {
	if g == nil {
		return nil, fmt.Errorf("gen: nil graph")
	}
	if err := validatePackages(g); err != nil {
		return nil, err
	}

	var files []File

	// Resource-driven detail/form pages, and the metadata the table pages and
	// registry need (route base, package, first table route for back-links).
	resources := make([]frontendView, 0, len(g.Resources))
	for _, resource := range g.Resources {
		if err := validateNames(resource); err != nil {
			return nil, err
		}
		view := newFrontendView(g, resource)
		resources = append(resources, view)

		pages := []struct {
			file string
			tmpl *template.Template
		}{
			{view.Type + "DetailPage.tsx", detailPageTemplate},
		}
		if view.Create || view.Update {
			pages = append(pages, struct {
				file string
				tmpl *template.Template
			}{view.Type + "FormPage.tsx", formPageTemplate})
		}
		for _, page := range pages {
			src, err := renderTS(page.tmpl, view)
			if err != nil {
				return nil, err
			}
			files = append(files, File{Path: path.Join(FrontendRoot, view.Package, page.file), Content: []byte(src)})
		}
	}

	// Page-driven table pages: one per resource_table page.
	tables := make([]tableView, 0, len(g.Pages))
	seen := make(map[string]string) // component name -> slug, guards a name collision
	for _, page := range g.Pages {
		if page.Spec.Type != spec.PageResourceTable {
			continue
		}
		view := newTableView(page)
		if other, dup := seen[view.Component]; dup {
			return nil, fmt.Errorf("gen: table pages %q and %q derive the same component name %q; rename one page slug",
				other, page.Spec.Slug, view.Component)
		}
		seen[view.Component] = page.Spec.Slug
		tables = append(tables, view)

		src, err := renderTS(tablePageTemplate, view)
		if err != nil {
			return nil, err
		}
		files = append(files, File{Path: path.Join(FrontendRoot, view.Package, view.Component+".tsx"), Content: []byte(src)})
	}

	registry, err := renderTS(registryTemplate, registryView{
		Banner:    tsBanner,
		Resources: resources,
		Tables:    tables,
	})
	if err != nil {
		return nil, err
	}
	files = append(files, File{Path: path.Join(FrontendRoot, "resources.tsx"), Content: []byte(registry)})

	return files, nil
}

// frontendView is the template data for one resource's detail and form pages.
type frontendView struct {
	Banner  string
	Package string // customer
	Type    string // Customer
	Title   string // Customers (plural label for headings/nav)

	// CollectionPath is the API collection path, e.g. "/api/v1/customers".
	CollectionPath string
	// RouteBase is the SPA route base for detail/form, e.g. "customers".
	RouteBase string
	// ListRoute is the route of this resource's first table page, e.g.
	// "customers", or "" when the resource has no table page — in which case the
	// detail/form "back to list" link is omitted.
	ListRoute string

	// CRUD toggles, mirrored from the resource behavior so the UI matches the
	// routes the handlers emit. Detail is always generated (reads).
	Create bool
	Update bool
	Delete bool

	Fields []frontendField
}

// tableView is the template data for one resource_table page.
type tableView struct {
	Banner    string
	Package   string // the bound resource's package, e.g. customer
	Component string // the component/file name, e.g. CustomersTablePage
	Type      string // the bound resource's code name, e.g. Customer

	Title string // TableConfig.Title, else the page label
	Slug  string // the page slug — the table's own route

	// CollectionPath is the bound resource's API collection path.
	CollectionPath string
	// RouteBase is the bound resource's route base, used for the row → detail
	// link and the "New" link so rows resolve to the resource's canonical
	// detail/form routes regardless of this table's own slug.
	RouteBase string
	// Create mirrors the resource behavior so the table shows a "New" link only
	// when the resource is writable.
	Create bool
	// PageSize is the rows-per-page the table requests, from TableConfig.PageSize
	// or defaultPageSize when unconfigured. The generated list handler already
	// paginates (query page/per_page, PageMeta), so the table honors it at
	// runtime without any Gombit change.
	PageSize int

	// Columns are the resolved table columns in order (the graph applies the
	// TableConfig.Columns → list fields → scalar fields default).
	Columns []frontendField
}

// defaultPageSize is the rows-per-page a resource_table page requests when it
// configures none, so every generated table paginates deterministically.
const defaultPageSize = 25

// frontendField is one field's projection into a table column and a form input.
type frontendField struct {
	JSONName    string // storage_name — the API/JSON key
	Label       string // human label for headings
	TSType      string // string | number | boolean
	Input       string // text | number | checkbox | select
	Placeholder string // format hint for text inputs (dates), or ""
	Options     []spec.EnumValue
	Required    bool
	// OmitEmpty marks a field whose wire type rejects an empty string, so an
	// empty value must be dropped from the request body rather than sent as "".
	// time.Time (date, datetime) and decimal.Decimal both reject ""; a missing
	// key unmarshals fine, and optional fields carry omitempty so the key is
	// optional in the request schema.
	OmitEmpty bool
}

// rfc3339Placeholder is the format hint shown in a date/datetime text input.
func rfc3339Placeholder(t spec.FieldType) string {
	if t == spec.TypeDate {
		return "YYYY-MM-DDT00:00:00Z"
	}
	return "YYYY-MM-DDTHH:MM:SSZ"
}

func newFrontendView(g *graph.Graph, resource *graph.Resource) frontendView {
	title := resource.Spec.LabelPlural
	if strings.TrimSpace(title) == "" {
		title = resource.Spec.Label
	}
	view := frontendView{
		Banner:         tsBanner,
		Package:        PackageName(resource),
		Type:           resource.CodeName(),
		Title:          title,
		CollectionPath: "/api/v1/" + kebab(resource.Spec.StorageName),
		RouteBase:      kebab(resource.Spec.StorageName),
		ListRoute:      firstTableRoute(g, resource),
		Create:         resource.Spec.Behavior.CreateEnabled,
		Update:         resource.Spec.Behavior.UpdateEnabled,
		Delete:         resource.Spec.Behavior.DeleteEnabled,
	}
	for _, field := range resource.Fields {
		view.Fields = append(view.Fields, frontendFieldFor(field))
	}
	return view
}

// firstTableRoute is the slug of the resource's first resource_table page, in
// authored page order, or "" when it has none — so a detail/form page links
// back to a real list and omits the link when there is none.
func firstTableRoute(g *graph.Graph, resource *graph.Resource) string {
	for _, page := range g.Pages {
		if page.Spec.Type == spec.PageResourceTable && page.Resource == resource {
			return page.Spec.Slug
		}
	}
	return ""
}

func newTableView(page *graph.Page) tableView {
	resource := page.Resource
	title := page.Spec.Label
	pageSize := defaultPageSize
	if page.Spec.Table != nil {
		if strings.TrimSpace(page.Spec.Table.Title) != "" {
			title = page.Spec.Table.Title
		}
		if page.Spec.Table.PageSize > 0 {
			pageSize = page.Spec.Table.PageSize
		}
	}
	view := tableView{
		Banner:         tsBanner,
		Package:        PackageName(resource),
		Component:      pascalSlug(page.Spec.Slug) + "TablePage",
		Type:           resource.CodeName(),
		Title:          title,
		Slug:           page.Spec.Slug,
		CollectionPath: "/api/v1/" + kebab(resource.Spec.StorageName),
		RouteBase:      kebab(resource.Spec.StorageName),
		Create:         resource.Spec.Behavior.CreateEnabled,
		PageSize:       pageSize,
	}
	for _, field := range page.Columns {
		view.Columns = append(view.Columns, frontendFieldFor(field))
	}
	return view
}

// pascalSlug turns a lower-kebab-case slug into a PascalCase identifier segment:
// "active-customers" -> "ActiveCustomers".
//
// It is injective over valid slugs, so two distinct slugs can never derive the
// same component name (which would make an already-committed revision fail to
// build — the #134 footgun). A letter-starting segment is PascalCased, marking
// the boundary with a capital; a digit-starting segment can't be upper-cased, so
// PascalCasing alone would erase its hyphen boundary ("a1" and "a-1" would both
// fold to "A1") — an underscore keeps the boundary, and since a valid slug never
// starts with a digit no leading underscore is ever produced. The component-name
// guard in Frontend is then pure belt-and-suspenders.
func pascalSlug(slug string) string {
	var b strings.Builder
	for _, part := range strings.Split(slug, "-") {
		if part == "" {
			continue
		}
		if c := part[0]; c >= '0' && c <= '9' {
			b.WriteByte('_')
			b.WriteString(part)
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

// frontendFieldFor maps a field to its TypeScript form representation.
func frontendFieldFor(field *graph.Field) frontendField {
	f := frontendField{
		JSONName: field.Spec.StorageName,
		Label:    field.Spec.Label,
		Required: field.Spec.Required,
		TSType:   "string",
		Input:    "text",
	}
	switch field.Spec.Type {
	case spec.TypeInteger, spec.TypeBelongsTo:
		f.TSType, f.Input = "number", "number"
	case spec.TypeDecimal:
		// A decimal is carried as a string to avoid float rounding. Like a
		// time, decimal.Decimal rejects "" on unmarshal, so an empty one is
		// omitted from the request body.
		f.TSType, f.Input, f.OmitEmpty = "string", "text", true
	case spec.TypeBoolean:
		f.TSType, f.Input = "boolean", "checkbox"
	case spec.TypeDate, spec.TypeDatetime:
		// The API carries these as time.Time, which marshals to RFC 3339 and
		// only unmarshals from RFC 3339. A native date/datetime-local control
		// produces "2026-08-29" / "2026-08-29T06:00", which the handler's
		// json.Unmarshal rejects, and cannot display the "…Z" wire value. So
		// the control is a text input holding the RFC 3339 string verbatim,
		// which round-trips; Placeholder documents the format. OmitEmpty drives
		// dropping an empty value from the request body on submit.
		f.Input, f.Placeholder, f.OmitEmpty = "text", rfc3339Placeholder(field.Spec.Type), true
	case spec.TypeEnum:
		f.Input, f.Options = "select", field.Spec.EnumValues
	case spec.TypeString, spec.TypeText:
		// text input, string type (the defaults)
	}
	return f
}

// registryView is the template data for resources.tsx.
type registryView struct {
	Banner    string
	Resources []frontendView
	Tables    []tableView
}

func renderTS(tmpl *template.Template, view any) (string, error) {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, view); err != nil {
		return "", fmt.Errorf("gen: execute %s template: %w", tmpl.Name(), err)
	}
	return buf.String(), nil
}
